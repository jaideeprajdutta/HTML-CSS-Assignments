function isLegal(age) {
    if (age >= 18) {
        console.log("You are legally an adult.");
    }
    else {
        console.log("You are not legally an adult.");
    }
}

for (let i = 0; i <= 18; i++) {
    isLegal(i);
}

while (age < 18) {
    console.log("You are not legally an adult.");
    age++;
}

